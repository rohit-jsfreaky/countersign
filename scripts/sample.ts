// The sample: public/samples/plan.json is a REAL `terraform show -json` plan, made with Terraform 1.17.2 and the
// hashicorp/aws provider from public/samples/main.tf against a sample state (no AWS account; ids and the password are
// made up). Sam Okafor and Lena Brandt are made up too. Writes docs/sample.json and templates/_shared/example.ts.
// Run: node --experimental-strip-types scripts/sample.ts
import { readFileSync, writeFileSync } from "node:fs";
import { parsePlan, toValues } from "../templates/_shared/plan.ts";
import { SAMPLE_META } from "../src/lib/sample.ts";


const plan = parsePlan(readFileSync(new URL("../public/samples/plan.json", import.meta.url), "utf8"));
const json = JSON.stringify(toValues(plan, { ...SAMPLE_META, date: "2026-11-22", decision: "conditions" }), null, 2);
writeFileSync(new URL("../docs/sample.json", import.meta.url), `${json}\n`);
writeFileSync(new URL("../templates/_shared/example.ts", import.meta.url), `// The sample: a real Terraform 1.17.2 plan (AWS provider) of a sample stack, public/samples/plan.json. People are made up.\n// Generated by scripts/sample.ts.\nconst example = ${json};\n\nexport default example;\n`);
console.log(plan.changes.map((c) => `${c.risk.padEnd(6)} ${c.action.padEnd(7)} ${c.address}`).join("\n"));
